QUOTE_RE = re.compile(r"“([^“”]*)”")
SINGLE_QUOTE_RE = re.compile(r"‘([^‘’]*)’")
CJK = "\u3400-\u9fff"


class Converter:
    def __init__(self):
        self.frozen = []

    def freeze(self, value):
        idx = len(self.frozen)
        self.frozen.append(value)
        return f"\ue000{idx}\ue001"

    def protect(self, text):
        return PROTECT_RE.sub(lambda m: self.freeze(m.group(0)), text)

    def apply_rules(self, text, rules):
        for src, dst in rules:
            if src in text:
                text = text.replace(src, self.freeze(dst))
        return text

    def apply_regexes(self, text, rules):
        for pattern, repl in rules:
            text = re.sub(pattern, lambda m, r=repl: self.freeze(m.expand(r)), text)
        return text

    def restore(self, text):
        return TOKEN_RE.sub(lambda m: self.frozen[int(m.group(1))], text)

    def convert(self, text):
        if not isinstance(text, str) or not text:
            return text
        self.frozen = []
        out = self.protect(text)
        out = self.apply_rules(out, PRE_RULES)
        out = self.apply_regexes(out, PRE_REGEX)
        out = S2TWP.convert(out)
        out = self.apply_rules(out, POST_RULES)
        out = self.apply_regexes(out, POST_REGEX)
        out = QUOTE_RE.sub(lambda m: "「" + m.group(1) + "」", out)
        out = SINGLE_QUOTE_RE.sub(lambda m: "『" + m.group(1) + "』", out)
        out = self.restore(out)
        out = space_latin(out)
        return out


def space_latin(text):
    for token in ("Agent", "QR Code", "Tab", "Enter", "Finder", "Dock"):
        pat = re.escape(token)
        text = re.sub(
            rf"(?<=[{CJK}])[ \t]*(?={pat}(?![A-Za-z]))", " ", text
        )
        text = re.sub(
            rf"(?<={pat})(?![A-Za-z])[ \t]*(?=[{CJK}])", " ", text
        )
    return text


def convert_value(value, converter=None):
    converter = converter or Converter()
    if isinstance(value, dict):
        return {k: convert_value(v, converter) for k, v in value.items()}
    if isinstance(value, list):
        return [convert_value(v, converter) for v in value]
    if isinstance(value, str):
        return converter.convert(value)
    return value


def convert_string(text):
    return Converter().convert(text)
